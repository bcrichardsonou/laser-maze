#!/usr/bin/env python3
"""ZoCo status transport. No remote command execution or physical-control code."""
import argparse
import datetime as dt
import json
import os
from pathlib import Path
import sqlite3
import time
import urllib.error
import urllib.parse
import urllib.request
import uuid

STATES = ('ready', 'running', 'faulted', 'maintenance', 'intentionally_off', 'unknown')


def utc_now():
    return dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%dT%H:%M:%S.%fZ')


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        raise ValueError('Redirect rejected; configure the final HTTPS endpoint')


# The portal accepts at most 40 flat metrics. Machine diagnostics are added to
# heartbeats after application status; redundant RFID details also exist in the
# separate live maintenance feed. Keep original durable events untouched.
def transport_payload(kind, payload):
    if kind not in ('heartbeat', 'status'):
        return payload
    metrics = payload.get('metrics', {})
    if not isinstance(metrics, dict):
        raise ValueError('Invalid metrics')
    if len(metrics) <= 40:
        return payload
    trimmed = dict(metrics)
    for name in ('rfid_scan_count', 'entry_state', 'rfid_reader_available'):
        if len(trimmed) <= 40:
            break
        trimmed.pop(name, None)
    if len(trimmed) > 40:
        raise ValueError('Too many metrics after RFID compatibility projection')
    return dict(payload, metrics=trimmed)


class Agent:
    def __init__(self, config_path):
        self.config = json.loads(Path(config_path).read_text())
        parsed = urllib.parse.urlsplit(self.config['url'])
        if parsed.scheme != 'https' or not parsed.hostname or parsed.username or parsed.password:
            raise ValueError('Use a direct HTTPS endpoint without embedded credentials')
        if parsed.fragment or parsed.query:
            raise ValueError('The logging endpoint must not contain query parameters')
        if not self.config.get('device_id') or len(self.config.get('upload_key', '')) < 48:
            raise ValueError('Use the configuration generated by the portal')
        if self.config['upload_key'].startswith('REPLACE_'):
            raise ValueError('Replace the upload key')
        path = Path(self.config['local_db']).expanduser()
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        self.db = sqlite3.connect(path, timeout=10)
        os.chmod(path, 0o600)
        self.db.execute('PRAGMA journal_mode=WAL')
        self.db.execute('PRAGMA synchronous=FULL')
        self.db.execute('CREATE TABLE IF NOT EXISTS identity (device_id TEXT NOT NULL)')
        identity = self.db.execute('SELECT device_id FROM identity').fetchone()
        if identity and identity[0] != self.config['device_id']:
            self.db.close()
            raise ValueError('This queue belongs to another device; use a different local_db path')
        if not identity:
            self.db.execute('INSERT INTO identity VALUES (?)', (self.config['device_id'],))
        self.db.execute('CREATE TABLE IF NOT EXISTS events (event_id TEXT PRIMARY KEY, occurred_at TEXT NOT NULL, kind TEXT NOT NULL, payload TEXT NOT NULL, sent INTEGER NOT NULL DEFAULT 0)')
        self.db.commit()

    def enqueue(self, kind, payload):
        import re
        if not re.fullmatch(r'[a-z][a-z0-9_]{0,39}', kind) or not isinstance(payload, dict):
            raise ValueError('Invalid event')
        if kind in ('heartbeat', 'status') and payload.get('state') not in STATES:
            raise ValueError('Invalid state')
        encoded = json.dumps(payload, allow_nan=False, ensure_ascii=False)
        if len(encoded.encode()) > 8192:
            raise ValueError('Event payload exceeds 8192 bytes')
        eid = str(uuid.uuid4())
        self.db.execute('INSERT INTO events(event_id,occurred_at,kind,payload) VALUES (?,?,?,?)',
                        (eid, utc_now(), kind, encoded))
        self.db.commit()
        return eid

    def pending(self):
        return self.db.execute('SELECT COUNT(*) FROM events WHERE sent=0').fetchone()[0]

    def make_batch(self):
        rows = self.db.execute('SELECT event_id,occurred_at,kind,payload FROM events WHERE sent=0 ORDER BY rowid LIMIT 100').fetchall()
        events = []
        for eid, when, kind, payload in rows:
            event = dict(event_id=eid, occurred_at=when, kind=kind, payload=transport_payload(kind, json.loads(payload)))
            # Bound the complete batch below the receiver's 256 KiB limit.
            candidate = {'device_id': self.config['device_id'], 'events': events + [event]}
            if len(json.dumps(candidate, ensure_ascii=False).encode()) > 240000:
                break
            events.append(event)
        return {'device_id': self.config['device_id'], 'events': events}

    def send_batch(self, body):
        request = urllib.request.Request(self.config['url'],
            data=json.dumps(body, allow_nan=False, ensure_ascii=False).encode(),
            headers={'Content-Type': 'application/json', 'Accept': 'application/json',
                     'User-Agent': 'ZoCo-Monitor/1.0', 'X-ZoCo-Key': self.config['upload_key']},
            method='POST')
        with urllib.request.build_opener(NoRedirect).open(request, timeout=10) as response:
            reply = json.loads(response.read(65536))
        expected = [event['event_id'] for event in body['events']]
        accepted = reply.get('accepted')
        if not isinstance(accepted, list) or not all(isinstance(x, str) for x in accepted) or len(accepted) != len(expected) or set(accepted) != set(expected):
            raise ValueError('Server did not acknowledge the complete batch')
        return len(expected)

    def upload_once(self):
        body = self.make_batch()
        if not body['events']:
            return 0
        count = self.send_batch(body)
        self.db.executemany('UPDATE events SET sent=1 WHERE event_id=?',
                            [(e['event_id'],) for e in body['events']])
        self.db.commit()
        return count

    def close(self):
        self.db.close()


def diagnostics():
    values = {}
    try:
        values['uptime_seconds'] = float(Path('/proc/uptime').read_text().split()[0])
    except (OSError, ValueError):
        pass
    try:
        values['temperature_c'] = round(float(Path('/sys/class/thermal/thermal_zone0/temp').read_text()) / 1000, 1)
    except (OSError, ValueError):
        pass
    return values


def read_status(path):
    # A stale sensor file cannot keep reporting that an exhibit is ready.
    if path is None:
        return {'state': 'unknown', 'metrics': {}}
    file = Path(path)
    if time.time() - file.stat().st_mtime > 120:
        return {'state': 'unknown', 'metrics': {}}
    data = json.loads(file.read_text())
    if not isinstance(data, dict) or data.get('state') not in STATES or not isinstance(data.get('metrics', {}), dict):
        raise ValueError('Invalid status file')
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('config', help='Private device-config.json generated by the portal')
    commands = parser.add_subparsers(dest='command', required=True)
    simulation = commands.add_parser('simulate', help='Send one labeled simulator heartbeat')
    simulation.add_argument('--state', choices=STATES, default='ready')
    simulation.add_argument('--fault', default='')
    simulation.add_argument('--queue-only', action='store_true')
    commands.add_parser('upload', help='Upload all queued events, with no new status')
    commands.add_parser('test', help='Send the same setup event twice to test deduplication')
    running = commands.add_parser('run', help='Report every minute; condition unknown without a status file')
    running.add_argument('--status-file', help='JSON written by the exhibit controller; use atomic replacement')
    args = parser.parse_args()
    agent = Agent(args.config)
    try:
        if args.command == 'test':
            eid = agent.enqueue('setup_test', {'message': 'ZoCo portal communication test'})
            row = agent.db.execute('SELECT occurred_at,payload FROM events WHERE event_id=?', (eid,)).fetchone()
            body = {'device_id': agent.config['device_id'], 'events': [dict(event_id=eid, occurred_at=row[0], kind='setup_test', payload=json.loads(row[1]))]}
            agent.send_batch(body)
            agent.send_batch(body)
            agent.db.execute('UPDATE events SET sent=1 WHERE event_id=?', (eid,))
            agent.db.commit()
            print('Upload and retry acknowledged. The exhibit log should show ONE setup_test event.')
        elif args.command == 'simulate':
            agent.enqueue('heartbeat', {'state': args.state, 'fault_summary': args.fault[:240],
                'metrics': {'usage_count': 12, 'cycles_since_refill': 12, 'software_version': 'laptop-simulator-v1', 'simulated': True}})
            if args.queue_only:
                print('Saved locally. No upload attempted.')
            else:
                while agent.upload_once():
                    time.sleep(1.1)
                print('Simulator report uploaded. Refresh the exhibit dashboard.')
        elif args.command == 'upload':
            total = 0
            while (count := agent.upload_once()):
                total += count
                time.sleep(1.1)
            print(f'Uploaded {total} queued events.')
        else:
            next_heartbeat = next_upload = 0.0
            retry = 5.0
            print('Monitoring started. Ctrl+C to stop. No physical controls are enabled.')
            while True:
                now = time.monotonic()
                if now >= next_heartbeat:
                    try:
                        status = read_status(args.status_file)
                    except (OSError, ValueError):
                        status = {'state': 'unknown', 'metrics': {}}
                    status.setdefault('metrics', {}).update(diagnostics())
                    status['metrics']['software_version'] = agent.config.get('software_version', 'unknown')
                    agent.enqueue('heartbeat', status)
                    next_heartbeat = now + 60
                if now >= next_upload:
                    try:
                        count = agent.upload_once()
                        retry = 1.1 if count and agent.pending() else 30.0
                    except (OSError, ValueError) as exc:
                        code = f' HTTP {exc.code}' if isinstance(exc, urllib.error.HTTPError) else ''
                        print(f'Upload deferred ({type(exc).__name__}{code}); events remain saved locally.')
                        retry = min(max(retry * 2, 5), 300)
                    next_upload = time.monotonic() + retry
                # Keep the local queue bounded for already-acknowledged events only.
                cutoff = (dt.datetime.now(dt.timezone.utc) - dt.timedelta(days=90)).strftime('%Y-%m-%dT%H:%M:%S.%fZ')
                agent.db.execute('DELETE FROM events WHERE sent=1 AND occurred_at<?', (cutoff,))
                agent.db.commit()
                time.sleep(0.5)
    except KeyboardInterrupt:
        print('\nMonitoring stopped; queued events remain on disk.')
    except (OSError, ValueError) as exc:
        code = f' HTTP {exc.code}' if isinstance(exc, urllib.error.HTTPError) else ''
        parser.exit(1, f'Test incomplete ({type(exc).__name__}{code}); queued events remain on disk. Check configuration and server logs.\n')
    finally:
        agent.close()


if __name__ == '__main__':
    main()
